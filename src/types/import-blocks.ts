// ============ pomocné funkce ============

export function generateBlockId(): string {
    return 'blk_' + Math.random().toString(36).slice(2, 10)
}

export function getBlockTypeLabel(type: BlockType): string {
    switch (type) {
        case 'kv': return 'Key-Value'
        case 'table': return 'Tabulka'
        case 'series': return 'Datová série'
        case 'stats': return 'Statistiky'
        case 'unknown': return 'Neznámé'
    }
}

export function getBlockActionLabel(action: BlockAction): string {
    switch (action) {
        case 'main_table': return 'Hlavní tabulka'
        case 'metadata': return 'Metadata'
        case 'series': return 'Série'
        case 'ignore': return 'Ignorováno'
    }
}
